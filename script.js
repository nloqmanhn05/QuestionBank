        function loadQuestion(chapKey, qIdx) {
            const chap = QUESTION_BANK[chapKey];
            const qData = chap.questions[qIdx];
            const savedState = userState[chapKey][qIdx];

            // Update Titles & Badges
            currentChapBadgeEl.textContent = `Chapter ${chapKey.replace('ch', '')}`;
            currentChapTitleEl.textContent = chap.title.replace(/^Chapter \d+:\s*/, '');
            qBadgeEl.textContent = `${qIdx + 1}.`;
            qNumberIndicatorEl.textContent = `Q ${qIdx + 1} / 30`;
            questionTextEl.textContent = qData.q;

            // Render Options
            optionsContainerEl.innerHTML = '';
            const optionLetters = ['A', 'B', 'C', 'D'];

            qData.options.forEach((optText, i) => {
                const isAnswered = savedState !== undefined;
                const optCard = document.createElement('div');

                let cardClasses = "option-card p-2.5 sm:p-3 rounded-xl flex items-center gap-3 cursor-pointer text-sm sm:text-base font-medium leading-snug";

                if (isAnswered) {
                    cardClasses += " disabled cursor-default";
                    if (i === qData.answer && savedState.chosen !== qData.answer) {
                        // Highlight correct answer when user answered wrong!
                        cardClasses += " highlight-correct";
                    } else if (i === savedState.chosen) {
                        if (savedState.isCorrect) {
                            cardClasses += " highlight-correct";
                        } else {
                            cardClasses += " selected-wrong";
                        }
                    }
                }

                optCard.className = cardClasses;

                let badgeStyle = "font-mono font-bold text-base sm:text-lg flex-shrink-0 min-w-[1.25rem]";
                let badgeInlineStyle = "color: var(--ink-soft);";

                if (isAnswered) {
                    if (i === qData.answer) {
                        badgeInlineStyle = "color: var(--correct); font-weight: bold;";
                    } else if (i === savedState.chosen && !savedState.isCorrect) {
                        badgeInlineStyle = "color: var(--wrong); font-weight: bold;";
                    }
                }

                optCard.innerHTML = `
                    <div class="${badgeStyle}" style="${badgeInlineStyle}">${optionLetters[i]}.</div>
                    <div class="flex-1" style="color: var(--ink);">${optText}</div>
                    ${isAnswered && i === qData.answer ? '<i class="fa-solid fa-circle-check text-lg ml-2" style="color: var(--correct);"></i>' : ''}
                    ${isAnswered && i === savedState.chosen && !savedState.isCorrect ? '<i class="fa-solid fa-circle-xmark text-lg ml-2" style="color: var(--wrong);"></i>' : ''}
                `;

                if (!isAnswered) {
                    optCard.onclick = () => handleOptionClick(chapKey, qIdx, i);
                }

                optionsContainerEl.appendChild(optCard);
            });

            // Handle Explanation & Feedback Panel visibility
            if (savedState !== undefined && !savedState.isCorrect) {
                feedbackPanelEl.classList.remove('hidden');
                feedbackPanelEl.className = "mt-3 p-4 rounded-xl transition-all duration-300";
                feedbackPanelEl.style.cssText = "background: var(--wrong-soft); border: 1.5px solid #e8cec3;";

                feedbackStatusHeaderEl.className = "flex items-center gap-2 mb-2 text-base font-bold";
                feedbackStatusHeaderEl.style.color = "var(--wrong)";
                feedbackStatusHeaderEl.innerHTML = `<i class="fa-solid fa-triangle-exclamation"></i> Incorrect Answer`;

                refSlideTextEl.textContent = qData.ref;
                explanationTextEl.textContent = qData.explanation;
            } else if (savedState !== undefined && savedState.isCorrect) {
                // If user selected correct, show victory callout
                feedbackPanelEl.classList.remove('hidden');
                feedbackPanelEl.className = "mt-3 p-4 rounded-xl transition-all duration-300";
                feedbackPanelEl.style.cssText = "background: var(--correct-soft); border: 1.5px solid #c7ddd2;";

                feedbackStatusHeaderEl.className = "flex items-center gap-2 mb-2 text-base font-bold";
                feedbackStatusHeaderEl.style.color = "var(--correct)";
                feedbackStatusHeaderEl.innerHTML = `<i class="fa-solid fa-circle-check"></i> Correct Answer`;

                refSlideTextEl.textContent = qData.ref;
                explanationTextEl.textContent = qData.explanation;
            } else {
                feedbackPanelEl.classList.add('hidden');
            }

            // Update navigation buttons state
            btnPrevQ.disabled = (qIdx === 0);
            btnNextQ.disabled = (qIdx === chap.questions.length - 1);

            renderQuestionGridNav();
            updateChapterProgress();
        }

        function handleOptionClick(chapKey, qIdx, chosenOptIndex) {
            const qData = QUESTION_BANK[chapKey].questions[qIdx];
            const isCorrect = (chosenOptIndex === qData.answer);

            userState[chapKey][qIdx] = {
                chosen: chosenOptIndex,
                isCorrect: isCorrect
            };

            loadQuestion(chapKey, qIdx);
            renderChapterSidebar();
            updateGlobalStats();
        }

        function renderQuestionGridNav() {
            questionGridNavEl.innerHTML = '';
            const chapState = userState[currentChapterKey] || {};
            const answeredCount = Object.keys(chapState).length;

            const quickJumpProgressEl = document.getElementById('quick-jump-progress');
            if (quickJumpProgressEl) {
                quickJumpProgressEl.textContent = `${answeredCount}/30`;
            }

            for (let i = 0; i < 30; i++) {
                const dotBtn = document.createElement('button');
                const qState = chapState[i];
                let style = "background: var(--paper); color: var(--ink-soft); border: 1.5px solid var(--card-line);";

                if (i === currentQuestionIndex) {
                    style += " outline: 2.5px solid var(--index); outline-offset: 1px; font-weight: bold;";
                }

                if (qState !== undefined) {
                    if (qState.isCorrect) {
                        style = "background: var(--correct); color: #fff; border: 1.5px solid var(--correct);";
                    } else {
                        style = "background: var(--wrong); color: #fff; border: 1.5px solid var(--wrong);";
                    }
                    if (i === currentQuestionIndex) {
                        style += " outline: 2.5px solid var(--ink); outline-offset: 1px;";
                    }
                }

                dotBtn.className = "w-full aspect-square rounded-xl text-xs font-mono font-semibold flex items-center justify-center transition hover:scale-105 cursor-pointer shadow-xs";
                dotBtn.style.cssText = style;
                dotBtn.textContent = i + 1;
                dotBtn.title = `Question ${i + 1}${qState ? (qState.isCorrect ? ' (Correct)' : ' (Incorrect)') : ''}`;
                dotBtn.onclick = () => {
                    currentQuestionIndex = i;
                    loadQuestion(currentChapterKey, currentQuestionIndex);
                };

                questionGridNavEl.appendChild(dotBtn);
            }
        }

        function updateChapterProgress() {
            const answeredCount = Object.keys(userState[currentChapterKey] || {}).length;
            const pct = (answeredCount / 30) * 100;
            chapProgressBarEl.style.width = `${pct}%`;
            chapProgressTextEl.textContent = `${answeredCount}/30`;
        }

        function updateGlobalStats() {
            let totalAnswered = 0;
            let totalCorrect = 0;

            Object.keys(userState).forEach(cKey => {
                Object.keys(userState[cKey]).forEach(qIdx => {
                    totalAnswered++;
                    if (userState[cKey][qIdx].isCorrect) {
                        totalCorrect++;
                    }
                });
            });

            globalScoreTextEl.textContent = `${totalCorrect} / 210`;
            const accuracy = totalAnswered > 0 ? Math.round((totalCorrect / totalAnswered) * 100) : 0;
            globalAccuracyTextEl.textContent = `${accuracy}%`;
        }

